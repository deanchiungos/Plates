/// Who moves where — and therefore whose plates you see far from home.
///
/// The gravity model in `PlateRarity` explains the plates around you by fleet size
/// and road distance, and it is right about nearly everything except the tail: the
/// California plate in a New Jersey car park did not diffuse there, somebody drove
/// it there, and they drove it along a tie — a move, a family, a job. Distance decay
/// has no way to see that a New Yorker is fifty times more likely to be in Florida
/// than a North Dakotan of equal remoteness.
///
/// Migration is the best free proxy for tie strength. Movers keep their old plates
/// for months, and the same ties that move households also generate the visits that
/// put far plates on local roads. The table is the IRS Statistics of Income state
/// migration file, tax year 2021 to 2022, counted in returns — roughly households.
/// A US government work, public domain, no attribution owed. Provinces are absent
/// because the IRS does not tax Canadians; the snowbird table below is the one
/// Canadian flow big enough to hand-set.
///
/// Regenerated by the session that created it from `stateoutflow2122.csv`; to
/// refresh, download the next vintage from irs.gov/pub/irs-soi and re-emit. The
/// ranking barely moves between vintages — interstate migration is slow-moving —
/// so staleness costs little.
enum PlateMigration {

    /// `ties(of: "CA", near: "NJ")` — how strongly California plates are tied to a
    /// New Jersey observer: households that moved CA to NJ, plus half the reverse
    /// flow, because ties pull traffic both ways but the mover's plate is the one
    /// that relocates. Zero for a plate observed in its own state — local traffic
    /// is the other term's job.
    static func ties(of code: String, near observer: String) -> Double {
        guard code != observer else { return 0 }
        return (flows[code]?[observer] ?? 0) + 0.5 * (flows[observer]?[code] ?? 0)
    }

    /// Canadian winter residents, in household-equivalents on the same scale as
    /// `flows`, keyed by host state. Hand-set, and flagged as such: seasonal
    /// residents file no change of address anywhere, so no administrative dataset
    /// counts them. The magnitudes lean on the one well-attested number — about a
    /// million Canadians winter in Florida, mostly from Ontario and Quebec — and on
    /// the western provinces preferring Arizona. Applied November through April.
    static let snowbirds: [String: [String: Double]] = [
        "FL": ["ON": 60000, "QC": 50000, "NB": 6000, "MB": 5000],
        "AZ": ["AB": 25000, "BC": 18000, "SK": 9000, "MB": 8000, "ON": 12000],
    ]

    static func snowbirdTies(of code: String, near observer: String,
                             winter: Bool) -> Double {
        guard winter else { return 0 }
        return snowbirds[observer]?[code] ?? 0
    }

    // MARK: - Data

    /// from to households, one triple per line. Parsed once; a packed string
    /// compiles in no time where a 2,550-entry dictionary literal would give the
    /// type checker a bad afternoon.
    static let flows: [String: [String: Double]] = {
        var out: [String: [String: Double]] = [:]
        for line in packed.split(separator: "\n") {
            let f = line.split(separator: " ")
            guard f.count == 3, let n = Double(f[2]) else { continue }
            out[String(f[0]), default: [:]][String(f[1])] = n
        }
        return out
    }()

